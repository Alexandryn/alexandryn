// --- FR-1: composition order — recovery, limits, logging, [auth,
// reserved], routing, each layer's own marker firing in that fixed
// sequence. ---

func TestChain_ComposesInFixedOrder(t *testing.T) {
	var order []string

	marker := func(name string) transporthttp.Middleware {
		return func(next http.Handler) http.Handler {
			return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				order = append(order, name)
				next.ServeHTTP(w, r)
			})
		}
	}

	routing := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		order = append(order, "routing")
	})

	handler := transporthttp.Chain(routing, marker("recovery"), marker("limits"), marker("logging"))

	req := httptest.NewRequest(http.MethodGet, "/", nil)
	handler.ServeHTTP(httptest.NewRecorder(), req)

	want := []string{"recovery", "limits", "logging", "routing"}
	if len(order) != len(want) {
		t.Fatalf("order = %v, want %v", order, want)
	}
	for i, name := range want {
		if order[i] != name {
			t.Fatalf("order = %v, want %v", order, want)
		}
	}
}

// --- FR-3: panic recovery ---

func TestRecovery_CatchesAPanicAndReturnsInternal(t *testing.T) {
	spy := testutil.NewSpyHandler()
	logger := slog.New(spy)
	ids := testutil.NewFakeIDGenerator("fallback-id-1")

	panicking := http.HandlerFunc(func(http.ResponseWriter, *http.Request) {
		panic("something went wrong")
	})

	handler := transporthttp.Recovery(logger, ids.NewID)(panicking)

	rec := httptest.NewRecorder()
	handler.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, "/", nil))

	if rec.Code != http.StatusInternalServerError {
		t.Fatalf("status = %d, want 500", rec.Code)
	}
	if ct := rec.Header().Get("Content-Type"); ct != "application/json" {
		t.Fatalf("Content-Type = %q, want application/json", ct)
	}

	var body struct {
		Code          string `json:"code"`
		Message       string `json:"message"`
		CorrelationID string `json:"correlationId"`
	}
	if err := json.Unmarshal(rec.Body.Bytes(), &body); err != nil {
		t.Fatalf("response body isn't valid JSON: %v\n%s", err, rec.Body.String())
	}
	if body.Code != "Internal" {
		t.Fatalf("code = %q, want Internal", body.Code)
	}
	if body.CorrelationID == "" {
		t.Fatal("correlationId is empty")
	}
	if strings.Contains(body.Message, "something went wrong") {
		t.Fatalf("panic message leaked into the client-facing body: %q", body.Message)
	}
}

