// --- FR-4: logging middleware skeleton ---

func TestLogging_EmitsDebugStartAndInfoCompletionWithTheSameCorrelationID(t *testing.T) {
	spy := testutil.NewSpyHandler()
	logger := slog.New(spy)
	ids := testutil.NewFakeIDGenerator("req-1")

	next := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusCreated)
	})
	handler := transporthttp.Logging(logger, ids.NewID)(next)

	req := httptest.NewRequest(http.MethodPost, "/widgets", nil)
	handler.ServeHTTP(httptest.NewRecorder(), req)

	records := spy.Records()
	if len(records) != 2 {
		t.Fatalf("got %d log records, want 2 (start + completion)", len(records))
	}

	start, completion := records[0], records[1]
	if start.Level != slog.LevelDebug {
		t.Fatalf("start record level = %v, want debug", start.Level)
	}
	if completion.Level != slog.LevelInfo {
		t.Fatalf("completion record level = %v, want info", completion.Level)
	}

	attrs := func(r slog.Record) map[string]string {
		m := map[string]string{}
		r.Attrs(func(a slog.Attr) bool {
			m[a.Key] = a.Value.String()
			return true
		})
		return m
	}

	startAttrs, completionAttrs := attrs(start), attrs(completion)

	if startAttrs["correlationId"] != "req-1" || completionAttrs["correlationId"] != "req-1" {
		t.Fatalf("correlation IDs = %q / %q, want both req-1", startAttrs["correlationId"], completionAttrs["correlationId"])
	}
	if completionAttrs["method"] != "POST" {
		t.Fatalf("completion method = %q, want POST", completionAttrs["method"])
	}
	if completionAttrs["path"] != "/widgets" {
		t.Fatalf("completion path = %q, want /widgets", completionAttrs["path"])
	}
	if completionAttrs["status"] != "201" {
		t.Fatalf("completion status = %q, want 201", completionAttrs["status"])
	}
	if completionAttrs["duration"] == "" {
		t.Fatal("completion duration attr is empty")
	}
}

